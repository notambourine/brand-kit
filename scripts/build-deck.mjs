#!/usr/bin/env node
// Compiles deck-standalone.css: deck.css plus every value, face, and logo it reads, as one
// Marp theme. marp-cli loads only the theme, so tokens.css on the page is not an option.
import { readFile, writeFile } from "node:fs/promises";

const read = (path) => readFile(new URL(`../${path}`, import.meta.url), "utf8");

// Fonts as data URIs: a PDF render or an emailed .html has no fonts/ beside it.
// Nunito is skipped; the lockup is outlined, so no slide sets the wordmark face.
const fonts = (await read("fonts.css"))
  .split(/(?=@font-face)/)
  .filter((block) => block.startsWith("@font-face") && !block.includes("Nunito"));
const faces = await Promise.all(
  fonts.map(async (block) => {
    const [, file] = /url\('\.\/(fonts\/[^']+)'\)/.exec(block);
    const bytes = await readFile(new URL(`../${file}`, import.meta.url));
    return block
      .replace(/url\('[^']+'\)/, `url(data:font/woff2;base64,${bytes.toString("base64")})`)
      .trim();
  }),
);

// Marpit rewrites `:root` to `section`; a bare `.theme-light` would only match inside a slide.
const vars = (await read("vars.css")).replace(/^\.theme-light \{/m, "section.theme-light {");
const deck = (await read("deck.css")).replace("/* @theme nt */", "");

await writeFile(
  new URL("../deck-standalone.css", import.meta.url),
  [
    "/* @theme nt */",
    "/* Generated by scripts/build-deck.mjs from deck.css. Pass to marp-cli as --theme-set. */",
    faces.join("\n"),
    vars,
    await read("logo-vars.css"),
    deck,
  ].join("\n"),
);
