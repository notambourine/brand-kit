#!/usr/bin/env node
// Compiles the self-contained exports: deck-standalone.css for marp-cli, which loads only
// the theme, and doc-standalone.css for a document PDF, which leaves with no fonts/ beside it.
import { readFile, writeFile } from "node:fs/promises";

const read = (path) => readFile(new URL(`../${path}`, import.meta.url), "utf8");
const write = (path, parts) => writeFile(new URL(`../${path}`, import.meta.url), parts.join("\n"));

// Fonts as data URIs: a PDF render or an emailed .html has no fonts/ beside it.
// Nunito is skipped; the lockup is outlined, so nothing here sets the wordmark face.
const fonts = (await read("fonts.css"))
  .split(/(?=@font-face)/)
  .filter((block) => block.startsWith("@font-face") && !block.includes("Nunito"));
const faces = (
  await Promise.all(
    fonts.map(async (block) => {
      const [, file] = /url\('\.\/(fonts\/[^']+)'\)/.exec(block);
      const bytes = await readFile(new URL(`../${file}`, import.meta.url));
      return block
        .replace(/url\('[^']+'\)/, `url(data:font/woff2;base64,${bytes.toString("base64")})`)
        .trim();
    }),
  )
).join("\n");
const vars = await read("vars.css");
const logo = await read("logo-vars.css");

// Marpit rewrites `:root` to `section`; a bare `.theme-light` would only match inside a slide.
await write("deck-standalone.css", [
  "/* @theme nt */",
  "/* Generated by scripts/build-standalone.mjs from deck.css. Pass to marp-cli as --theme-set. */",
  faces,
  vars.replace(/^\.theme-light \{/m, "section.theme-light {"),
  logo,
  (await read("deck.css")).replace("/* @theme nt */", ""),
]);

await write("doc-standalone.css", [
  "/* Generated by scripts/build-standalone.mjs from prose.css and print.css. */",
  faces,
  vars,
  logo,
  await read("elements.css"),
  await read("prose.css"),
  await read("print.css"),
]);
